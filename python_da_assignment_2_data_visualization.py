import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
# Load the 'taxis' dataset
df = sns.load_dataset("taxis")
df

df.isnull().sum()

df.isnull().sum()[df.isnull().sum()>0]

df.info()

df.select_dtypes(include="number").columns

df.select_dtypes(include="object").columns

df = df.drop_duplicates()

df.duplicated().sum()

df[["payment", "pickup_zone", "dropoff_zone", "pickup_borough", "dropoff_borough"]].mode()

df = df.copy()

df.loc[:, "payment"] = df["payment"].fillna(df["payment"].mode()[0])
df.loc[:, "pickup_zone"] = df["pickup_zone"].fillna(df["pickup_zone"].mode()[0])
df.loc[:, "dropoff_zone"] = df["dropoff_zone"].fillna(df["dropoff_zone"].mode()[0])
df.loc[:, "pickup_borough"] = df["pickup_borough"].fillna(df["pickup_borough"].mode()[0])
df.loc[:, "dropoff_borough"] = df["dropoff_borough"].fillna(df["dropoff_borough"].mode()[0])

df.isnull().sum()

df.head()

df.duplicated().sum()

df["pickup"]=pd.to_datetime(df["pickup"])

df=df.sort_values(by="pickup")

plt.figure(figsize=(10,5))
plt.plot(df["pickup"],df["fare"])
plt.xlabel("pickup")
plt.ylabel("fare")
plt.title("Fare over Time")
plt.show()

borough_fare = df.groupby("pickup_borough")["fare"].sum()
borough_fare

plt.figure(figsize=(10,5))
plt.bar(borough_fare.index,borough_fare.values)
plt.xlabel("pickup_borough")
plt.ylabel("fare")
plt.title("Total Fare by Pickup Borough")
plt.show()

df["payment"].value_counts().plot(kind="pie",
autopct="%1.1f%%",
    figsize=(6,6)
)
plt.title("Distribution of Trips")
plt.ylabel("")
plt.show()

plt.figure(figsize=(8,6))
sns.histplot(x="distance",data=df,kde=True,bins=20)
plt.title("Distribution of Taxi Trip Distance")
plt.xlabel("Distance")
plt.ylabel("Frequency")
plt.show()

plt.figure(figsize=(8,6))
sns.boxplot(x="pickup_borough",y="tip",data=df)
plt.title("Distribution of Tips by Pickup Borough")
plt.xlabel("Pickup Borough")
plt.ylabel("Tip")
plt.show()

sns.countplot(x="pickup_borough",data=df)
plt.xlabel("Pickup Borough")
plt.ylabel("Count of Trips")
plt.title("Distribution of Trips by Pickup Borough")
plt.show()

plt.figure(figsize=(7,6))
sns.scatterplot(x="distance",y="fare",data=df,hue="pickup_borough")
plt.xlabel("Distance")
plt.ylabel("Fare")
plt.title("Relationship Between Distance and Fare")

df1 = df[['passengers', 'distance', 'fare', 'tip', 'tolls', 'total']]
corr = df1.corr()
plt.figure(figsize=(8,6))
sns.heatmap(corr, annot=True, cmap="coolwarm")
plt.title("Correlation Heatmap")
plt.show()

sns.pairplot(data=df,vars=['passengers', 'distance', 'fare', 'tip', 'tolls', 'total'],hue="pickup_zone")
plt.show()

plt.figure(figsize=(8,6))
sns.violinplot(x="payment",y="fare",data=df)
plt.xlabel("payment method")
plt.ylabel("fare")
plt.title("Distribution of Fare for each Payment Method.")
plt.show()